#nullable enable
using System;
using System.Collections.Generic;
using Unity.Mathematics;
using UnityEngine;

public class ShapeBehaviour : MonoBehaviour
{
    [SerializeField]
    protected List<ShapeNode> nodes = new();
    public IReadOnlyList<ShapeNode> Nodes => nodes;

    private readonly HashSet<ShapeNode> activatedNodes = new();

    public bool IsCompleted => activatedNodes.Count == nodes.Count;

    public ShapeNode? Click(in Vector2 mousePosition)
    {
        foreach (ShapeNode node in this.nodes)
        {
            if (node.Click(mousePosition)) {
                this.activatedNodes.Add(node);
                return node;
            }
        }
        return null;
    }

    public void Reset()
    {
        this.activatedNodes.Clear();
        foreach (ShapeNode node in this.nodes)
        {
            node.activated = false;
        }
    }

    [Serializable]
    public class ShapeNode
    {
        private const float SUCCESS_RADIUS = 0.25f;

        [SerializeField]
        public Transform? transform;

        [SerializeField]
        public Transform? connectedLeft;

        [SerializeField]
        public Transform? connectedRight;
        
        public bool activated = false;

        public bool Click(in Vector2 mousePosition)
        {
            if (this.transform == null)
                return false;
            if (this.TrySnapToSegment(mousePosition) != null)
            {
                this.activated = true;
                return true;
            }
            return false;
        }

        public Vector2? TrySnapToSegment(in Vector2 mousePosition)
        {
            if (this.transform == null)
                return null;
            Vector2 origin = this.transform.position;
            Vector2? left = TrySnapToSegment(origin, this.connectedLeft, mousePosition);
            if (left != null)
                return left;
            Vector2? right = TrySnapToSegment(origin, this.connectedRight, mousePosition);
            return right;
        }

        // Derived from code generated by Claude Opus 5.5
        private static Vector2? TrySnapToSegment(in Vector2 origin, in Transform? connected,
                in Vector2 mousePosition)
        {
            if (connected == null)
                return null;
            Vector2 segment = (Vector2)connected.position - origin;
            float lengthSq = segment.sqrMagnitude;
            if (lengthSq < Mathf.Epsilon)
            {
                if ((mousePosition - origin).sqrMagnitude <= SUCCESS_RADIUS * SUCCESS_RADIUS)
                {
                    return origin;
                }
                return null;
            }
            float t = Vector2.Dot(mousePosition - origin, segment) / lengthSq;
            if (t > 0.5f)
                return null;
            Vector2 closest = origin + segment * Mathf.Max(t, 0f);
            if ((mousePosition - closest).sqrMagnitude <= SUCCESS_RADIUS * SUCCESS_RADIUS)
            {
                return closest;
            }
            return null;
        }
    }
}